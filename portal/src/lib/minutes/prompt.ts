export interface MinutesRequest {
  project: string;
  title: string;
  date: string;
  place: string;
  attendees: string;
  distribute: boolean;
  memo: string;
  transcript: string;
}

export function minutesUserMessage(r: MinutesRequest) {
  return [
    "## 회의 정보",
    `- 프로젝트: ${r.project || "(없음)"}`,
    `- 회의 제목: ${r.title || "(없음)"}`,
    `- 일시: ${r.date || "(전사에서 찾기)"}`,
    `- 장소: ${r.place || "(전사에서 찾기)"}`,
    `- 참석자: ${r.attendees || "(전사에서 찾기)"}`,
    `- 배포 여부: ${r.distribute ? "배포용 — 참석자에게 보낸다" : "내부용 — 위키에만 남긴다"}`,
    "",
    "## 회의 중 메모",
    r.memo.trim() || "(없음)",
    "",
    "## 녹음 전사본",
    r.transcript.trim(),
  ].join("\n");
}
